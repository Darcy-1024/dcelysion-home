"""Rebuild checked-in MiSans webfont chunks; ordinary builds need no Python."""
from pathlib import Path
import hashlib
import json
import io
from concurrent.futures import ProcessPoolExecutor
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'resources/fonts/MiSansVF.woff2'
OUTPUT = ROOT / 'public/assets/fonts/misans'


def build_chunk(group):
    label, points = group
    font = TTFont(SOURCE, recalcTimestamp=False)
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.name_legacy = True
    options.recalc_timestamp = False
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points)
    worker.subset(font)
    font.flavor = 'woff2'
    buffer = io.BytesIO()
    font.save(buffer)
    content = buffer.getvalue()
    filename = f'{label}-{hashlib.sha256(content).hexdigest()[:12]}.woff2'
    (OUTPUT / filename).write_bytes(content)
    return filename, len(content)


def ranges(points):
    result = []
    for point in sorted(points):
        if result and point == result[-1][1] + 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in result)


def main():
    source_font = TTFont(SOURCE)
    supported = set(source_font.getBestCmap())
    axes = [(a.axisTag, a.minValue, a.maxValue) for a in source_font['fvar'].axes]
    source_font.close()
    # Include source strings, configured names, Latin and common punctuation.
    # New/dynamic characters not in this set still load from the remaining chunks.
    common = set(range(32, 256)) | set(range(0x2000, 0x2070))
    for file in sorted((ROOT / 'src').rglob('*')):
        if file.suffix in {'.svelte', '.ts', '.astro', '.json'} and '.test.' not in file.name:
            common.update(map(ord, file.read_text(encoding='utf-8')))
    common &= supported
    remaining = sorted(supported - common)
    groups = [('common', common)] + [
        (f'{i // 512:03}', set(remaining[i:i + 512]))
        for i in range(0, len(remaining), 512)
    ]
    OUTPUT.mkdir(parents=True, exist_ok=True)
    css = ['/* Generated by scripts/split-font.py. MiSans by Xiaomi; glyph outlines and variable weights preserved. */']
    records, covered, keep = [], set(), set()
    with ProcessPoolExecutor(max_workers=4) as pool:
        results = list(pool.map(build_chunk, groups))
    for (label, points), (filename, size) in zip(groups, results):
        keep.add(filename)
        with TTFont(OUTPUT / filename) as check:
            actual = set(check.getBestCmap())
            assert actual == points, f'Character coverage mismatch: {label}'
            assert [(a.axisTag, a.minValue, a.maxValue) for a in check['fvar'].axes] == axes
        assert not covered & actual
        covered |= actual
        css.append("@font-face { font-family: 'MiSans VF'; src: url('/assets/fonts/misans/" + filename + "') format('woff2'); font-weight: 150 700; font-style: normal; font-display: swap; unicode-range: " + ranges(points) + '; }')
        records.append({'file': filename, 'characters': len(points), 'bytes': size})
    assert covered == supported
    (ROOT / 'src/styles/misans.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
    manifest = {'sourceSha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(), 'characters': len(supported), 'chunks': records}
    (OUTPUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    # Only remove obsolete generated chunks inside this fixed output directory.
    for file in OUTPUT.glob('*.woff2'):
        if file.name not in keep:
            file.unlink()
    print(json.dumps({'characters': len(covered), 'chunks': len(records), 'commonBytes': records[0]['bytes'], 'totalBytes': sum(r['bytes'] for r in records)}))


if __name__ == '__main__':
    main()
